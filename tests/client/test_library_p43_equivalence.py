def test_cli_import_check_reports_a_gap_and_exits_one(
    repo: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    from studio_client.cli import main

    agent = repo / ".claude" / "agents" / f"{AGENT_KEY}.md"
    agent.write_text(agent.read_text(encoding="utf-8") + "\nlocal edit\n", encoding="utf-8")
    with pytest.raises(SystemExit) as exit_info:
        main(["library", "import-check", "--repo-root", str(repo), "--json"])
    assert exit_info.value.code == 1
    payload = capsys.readouterr().out
    assert f".claude/agents/{AGENT_KEY}.md" in payload
    assert '"failures": 1' in payload
    assert '"unprojected": 0' in payload


def test_real_repository_import_check_has_zero_gaps() -> None:
    """End-to-end on the real depot: `build_publish_items` + `check_equivalence`
    reports no blocking gap and nothing unprojected (`excluded` stays listed)."""

    from studio_client.publish import build_publish_items

    real_repo = Path(__file__).resolve().parents[2]
    differences = check_equivalence(real_repo, items=build_publish_items(real_repo))
    blocking = [item for item in differences if item.nature.blocking]
    assert blocking == []
    assert [item for item in differences if item.nature is DifferenceNature.UNPROJECTED] == []
