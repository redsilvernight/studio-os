"""P43 — Library equivalence gate (`studio-client library import-check`).

The projections compared here are the committed ones, generated by the
existing file-based pipeline (adapters over `build_offline_resolved`,
`render_claude_rule`, `render_skill`) from a minimal `.agents/` source. The
check rebuilds the same files from fabricated Library items — `rule/v2`,
`agent_definition/v2`, `skill/v1`, `model_profile/v1` — so it proves the
Library content alone carries the projection surface.

Tests run on fabricated `PublishItem`s on purpose: `build_publish_items` still
emits the v1 payloads (the `rule/v2` + `agent/v2` migration is a separate
workstream), and the check accepts injected items for exactly that window.

The projections the check rebuilds are the ones the repository commits today:
`build_offline_resolved` + the three local adapters, `render_claude_rule`, and
`skill_sync.render_skill` for the Library skill envelope.
"""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path

import pytest

# Same guard as `tests/mcp/test_roadmaps_p4.py`: when the interpreter resolves
# `studio_client` from another checkout (an installed venv whose `.pth` files
# point at the main repository), the worktree module is invisible and a hard
# import error would abort the whole `-x` run instead of skipping this file.
pytest.importorskip("studio_client.library_equivalence")

from studio_client.adapters import get_adapter  # noqa: E402
from studio_client.canonical import (  # noqa: E402
    build_offline_resolved,
    load_rule_meta,
    render_claude_rule,
)
from studio_client.context.library import LibraryContextItem  # noqa: E402
from studio_client.library_equivalence import (  # noqa: E402
    Difference,
    DifferenceNature,
    check_equivalence,
)
from studio_client.publish import PublishItem  # noqa: E402
from studio_client.skill_sync import render_skill  # noqa: E402

AGENT_KEY = "demo"
AGENT_BODY = "You review changes before they merge.\n"
RULE_KEY = "review"
RULE_TEXT = "# Review discipline\n\nRead the diff before anything else.\n"
RULE_GLOBS = ["src/**/*.py"]
SKILL_KEY = "demo-skill"
SKILL_DESCRIPTION = "Demo skill for the P43 equivalence check."
SKILL_TEXT = "# Demo skill\n\nDo the thing, then report.\n"
PROFILE_KEY = "demo-profile"

AGENT_SOURCE = f"""---
stable_key: {AGENT_KEY}
title: Demo Agent
summary: Review changes proportionally to risk.
intended_use: Use before merging a change.
triggers:
  - before merging
edit_policy: deny
tools: [read, grep]
requirements:
  reasoning: medium
rules: [{RULE_KEY}]
skills: [{SKILL_KEY}]
---

{AGENT_BODY}"""

RULE_SOURCE = f"""---
name: {RULE_KEY}
stable_key: {RULE_KEY}
applies_to: [{", ".join(f'"{glob}"' for glob in RULE_GLOBS)}]
---

{RULE_TEXT}"""

SKILL_SOURCE = f"""---
name: {SKILL_KEY}
description: {SKILL_DESCRIPTION}
---

{SKILL_TEXT}"""


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def _items() -> list[PublishItem]:
    """The Library payloads a finished migration would publish from `.agents/`."""

    return [
        PublishItem(
            "rule",
            RULE_KEY,
            RULE_KEY,
            {
                "content_schema": "studio.library.rule/v2",
                "text": RULE_TEXT,
                "applies_to": list(RULE_GLOBS),
            },
        ),
        PublishItem(
            "skill",
            SKILL_KEY,
            SKILL_DESCRIPTION,
            {"content_schema": "studio.library.skill/v1", "text": SKILL_TEXT},
        ),
        PublishItem(
            "model_profile",
            PROFILE_KEY,
            "Demo profile",
            {
                "content_schema": "studio.library.model_profile/v1",
                "requirements": {"reasoning": "medium"},
            },
        ),
        PublishItem(
            "agent",
            AGENT_KEY,
            "Demo Agent",
            {
                "content_schema": "studio.library.agent_definition/v2",
                "summary": "Review changes proportionally to risk.",
                "intended_use": "Use before merging a change.",
                "instructions": AGENT_BODY,
                "triggers": ["before merging"],
                "edit_policy": "deny",
                "tools": ["read", "grep"],
            },
            (("rule", RULE_KEY), ("skill", SKILL_KEY), ("model_profile", PROFILE_KEY)),
        ),
    ]


def _write_committed_projections(root: Path) -> None:
    """Generate the committed projections the way the repository does today:
    the harness adapters over the canonical `.agents/` files, the rule through
    `render_claude_rule`, the skill through the Library renderer."""

    resolved = build_offline_resolved(root, AGENT_KEY)
    for adapter_id in ("claude-code", "codex", "opencode"):
        adapter = get_adapter(adapter_id)
        for artifact in adapter.translate(resolved).artifacts:
            _write(root.joinpath(*artifact.path.split("/")), artifact.content)
    applies_to, body = load_rule_meta(root, RULE_KEY)
    _write(
        root / ".claude" / "rules" / f"{RULE_KEY}.md",
        render_claude_rule(RULE_KEY, applies_to, body),
    )
    projection = LibraryContextItem(
        library_kind="skill",
        stable_key=SKILL_KEY,
        version=1,
        version_origin="active",
        scope="studio",
        title=SKILL_DESCRIPTION,
        text=SKILL_TEXT,
        content_schema="studio.library.skill/v1",
    )
    rendered = render_skill(projection)
    for harness in (".claude", ".codex", ".opencode"):
        _write(root / harness / "skills" / SKILL_KEY / "SKILL.md", rendered)


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    """Minimal repository: one agent, one rule, one skill and their committed
    projections for the three harnesses."""

    _write(tmp_path / ".agents" / "definitions" / f"{AGENT_KEY}.md", AGENT_SOURCE)
    _write(tmp_path / ".agents" / "rules" / f"{RULE_KEY}.md", RULE_SOURCE)
    _write(tmp_path / ".agents" / "skills" / SKILL_KEY / "SKILL.md", SKILL_SOURCE)
    _write_committed_projections(tmp_path)
    return tmp_path


def test_library_projection_matches_the_committed_files(repo: Path) -> None:
    assert check_equivalence(repo, items=_items()) == []


@pytest.mark.parametrize(
    "relative",
    (
        f".claude/agents/{AGENT_KEY}.md",
        f".codex/agents/{AGENT_KEY}.toml",
        f".opencode/agents/{AGENT_KEY}.md",
        f".claude/rules/{RULE_KEY}.md",
    ),
)
def test_altered_projection_is_reported(repo: Path, relative: str) -> None:
    target = repo.joinpath(*relative.split("/"))
    target.write_text(target.read_text(encoding="utf-8") + "\nlocal edit\n", encoding="utf-8")
    differences = check_equivalence(repo, items=_items())
    assert [Difference(relative, DifferenceNature.CONTENT)] == [
        Difference(item.path, item.nature) for item in differences
    ]


def test_altered_skill_copy_is_reported(repo: Path) -> None:
    relative = f".codex/skills/{SKILL_KEY}/SKILL.md"
    target = repo.joinpath(*relative.split("/"))
    target.write_text(SKILL_SOURCE, encoding="utf-8")
    differences = check_equivalence(repo, items=_items())
    assert [(item.path, item.nature) for item in differences] == [
        (relative, DifferenceNature.CONTENT)
    ]


def test_missing_and_unexpected_files_are_reported(repo: Path) -> None:
    codex_agent = repo / ".codex" / "agents" / f"{AGENT_KEY}.toml"
    codex_agent.unlink()
    stray = repo / ".claude" / "agents" / "handwritten.md"
    _write(stray, "---\nname: handwritten\n---\n")
    differences = {item.path: item.nature for item in check_equivalence(repo, items=_items())}
    assert differences[f".codex/agents/{AGENT_KEY}.toml"] is DifferenceNature.MISSING
    assert differences[".claude/agents/handwritten.md"] is DifferenceNature.UNEXPECTED


def test_out_of_library_fields_are_listed_not_ignored(repo: Path) -> None:
    _write(repo / ".agents" / "rules" / "studio-protocol.md", "---\nname: studio-protocol\n---\n")
    _write(repo / "AGENTS.md", "<!-- BEGIN GENERATED RULES from .agents/rules -->\n")
    differences = check_equivalence(repo, items=_items())
    excluded = {item.path for item in differences if item.nature is DifferenceNature.EXCLUDED}
    assert excluded == {".agents/rules/studio-protocol.md", "AGENTS.md"}
    assert [item for item in differences if item.nature is not DifferenceNature.EXCLUDED] == []


def test_v1_rule_content_cannot_reproduce_the_rule_projection(repo: Path) -> None:
    """Documents why `rule/v2` is required: a v1 payload has no `applies_to`."""

    items: Sequence[PublishItem] = [
        PublishItem(
            "rule",
            RULE_KEY,
            RULE_KEY,
            {"content_schema": "studio.library.rule/v1", "text": RULE_TEXT},
        ),
        *[item for item in _items() if item.kind != "rule"],
    ]
    differences = check_equivalence(repo, items=items)
    assert [(item.path, item.nature) for item in differences] == [
        (f".claude/rules/{RULE_KEY}.md", DifferenceNature.CONTENT)
    ]


def test_cli_import_check_reports_a_gap_and_exits_one(
    repo: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    from studio_client.cli import main

    agent = repo / ".claude" / "agents" / f"{AGENT_KEY}.md"
    agent.write_text(agent.read_text(encoding="utf-8") + "\nlocal edit\n", encoding="utf-8")
    with pytest.raises(SystemExit) as exit_info:
        main(["library", "import-check", "--repo-root", str(repo), "--json"])
    assert exit_info.value.code == 1
    payload = capsys.readouterr().out
    assert f".claude/agents/{AGENT_KEY}.md" in payload
