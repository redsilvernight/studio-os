"""P43 — Library equivalence gate (`studio-client library import-check`).

The projections compared here are the committed ones, generated by the
existing file-based pipeline: the harness adapters over `build_offline_resolved`
for agents, `render_claude_rule` for rules, and the committed skill mechanism
for skills — `skill_projections_from` (every skill in `.claude`/`.codex`/
`.opencode`, verbatim `SKILL.md` plus `references/`). The check rebuilds the
same files from fabricated Library items — `rule/v2`, `agent_definition/v2`,
`skill/v2` (frontmatter stripped, `disable_model_invocation` flag, `files[]`
for references), `model_profile/v1` — so it proves the Library content alone
carries the projection surface.

Tests run on fabricated `PublishItem`s on purpose: `build_publish_items` emits
the v2 payloads, and the check accepts injected items for exactly that window.

Three behaviours are pinned: every skill is projected into every harness (a
missing skill file is a blocking `missing` gap); the
`disable-model-invocation` frontmatter key is carried by the Library (no gap);
any other uncarried frontmatter key is a real `content` gap naming the field.
"""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path

import pytest

# Same guard as `tests/mcp/test_roadmaps_p4.py`: when the interpreter resolves
# `studio_client` from another checkout (an installed venv whose `.pth` files
# point at the main repository), the worktree module is invisible and a hard
# import error would abort the whole `-x` run instead of skipping this file.
pytest.importorskip("studio_client.library_equivalence")

from studio_client.adapters import get_adapter  # noqa: E402
from studio_client.canonical import (  # noqa: E402
    build_offline_resolved,
    load_rule_meta,
    render_claude_rule,
)
from studio_client.library_equivalence import (  # noqa: E402
    Difference,
    DifferenceNature,
    check_equivalence,
)
from studio_client.publish import PublishItem  # noqa: E402

AGENT_KEY = "demo"
AGENT_BODY = "You review changes before they merge.\n"
RULE_KEY = "review"
RULE_TEXT = "# Review discipline\n\nRead the diff before anything else.\n"
RULE_GLOBS = ["src/**/*.py"]
SKILL_KEY = "studio-task"
SKILL_DESCRIPTION = "Demo workflow skill for the P43 equivalence check."
SKILL_TEXT = "# Demo skill\n\nDo the thing, then report.\n"
SKILL_AUX_PATH = "references/setup.md"
SKILL_AUX_TEXT = "# Setup\n\nRun the checks.\n"
EXTRA_SKILL_KEY = "extra-skill"
EXTRA_SKILL_TEXT = "# Extra skill\n\nNever projected into codex/opencode.\n"
PROFILE_KEY = "demo-profile"

AGENT_SOURCE = f"""---
stable_key: {AGENT_KEY}
title: Demo Agent
summary: Review changes proportionally to risk.
intended_use: Use before merging a change.
triggers:
  - before merging
edit_policy: deny
tools: [read, grep]
requirements:
  reasoning: medium
rules: [{RULE_KEY}]
skills: [{SKILL_KEY}]
---

{AGENT_BODY}"""

RULE_SOURCE = f"""---
name: {RULE_KEY}
stable_key: {RULE_KEY}
applies_to: [{", ".join(f'"{glob}"' for glob in RULE_GLOBS)}]
---

{RULE_TEXT}"""


def _skill_source(key: str, description: str, text: str) -> str:
    return f"---\nname: {key}\ndescription: {description}\n---\n\n{text}"


SKILL_SOURCE = _skill_source(SKILL_KEY, SKILL_DESCRIPTION, SKILL_TEXT)


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def _skill_item(
    key: str,
    description: str,
    text: str,
    files: Sequence[tuple[str, str]] = (),
    *,
    disable_model_invocation: bool = False,
) -> PublishItem:
    content: dict[str, object] = {
        "content_schema": "studio.library.skill/v2",
        "text": text,
        "disable_model_invocation": disable_model_invocation,
    }
    if files:
        content["files"] = [{"path": path, "text": value} for path, value in files]
    return PublishItem("skill", key, description, content)


def _items() -> list[PublishItem]:
    """The Library payloads a finished migration would publish from `.agents/`."""

    return [
        PublishItem(
            "rule",
            RULE_KEY,
            RULE_KEY,
            {
                "content_schema": "studio.library.rule/v2",
                "text": RULE_TEXT,
                "applies_to": list(RULE_GLOBS),
            },
        ),
        _skill_item(
            SKILL_KEY, SKILL_DESCRIPTION, SKILL_TEXT, files=((SKILL_AUX_PATH, SKILL_AUX_TEXT),)
        ),
        PublishItem(
            "model_profile",
            PROFILE_KEY,
            "Demo profile",
            {
                "content_schema": "studio.library.model_profile/v1",
                "requirements": {"reasoning": "medium"},
            },
        ),
        PublishItem(
            "agent",
            AGENT_KEY,
            "Demo Agent",
            {
                "content_schema": "studio.library.agent_definition/v2",
                "summary": "Review changes proportionally to risk.",
                "intended_use": "Use before merging a change.",
                "instructions": AGENT_BODY,
                "triggers": ["before merging"],
                "edit_policy": "deny",
                "tools": ["read", "grep"],
            },
            (("rule", RULE_KEY), ("skill", SKILL_KEY), ("model_profile", PROFILE_KEY)),
        ),
    ]


def _write_committed_projections(root: Path) -> None:
    """Generate the committed projections the way the repository does: the
    harness adapters over the canonical `.agents/` files, `render_claude_rule`,
    the verbatim `.claude` skill copy (references included) and the workflow
    entry points in every harness."""

    resolved = build_offline_resolved(root, AGENT_KEY)
    for adapter_id in ("claude-code", "codex", "opencode"):
        adapter = get_adapter(adapter_id)
        for artifact in adapter.translate(resolved).artifacts:
            _write(root.joinpath(*artifact.path.split("/")), artifact.content)
    applies_to, body = load_rule_meta(root, RULE_KEY)
    _write(
        root / ".claude" / "rules" / f"{RULE_KEY}.md",
        render_claude_rule(RULE_KEY, applies_to, body),
    )
    for harness in (".claude", ".codex", ".opencode"):
        _write(root / harness / "skills" / SKILL_KEY / "SKILL.md", SKILL_SOURCE)
        _write(
            root / harness / "skills" / SKILL_KEY / SKILL_AUX_PATH,
            SKILL_AUX_TEXT,
        )


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    """Minimal repository: one agent, one rule, one workflow skill (with a
    reference) and their committed projections for the three harnesses."""

    _write(tmp_path / ".agents" / "definitions" / f"{AGENT_KEY}.md", AGENT_SOURCE)
    _write(tmp_path / ".agents" / "rules" / f"{RULE_KEY}.md", RULE_SOURCE)
    _write(
        tmp_path / ".agents" / "skills" / SKILL_KEY / SKILL_AUX_PATH,
        SKILL_AUX_TEXT,
    )
    _write(tmp_path / ".agents" / "skills" / SKILL_KEY / "SKILL.md", SKILL_SOURCE)
    _write_committed_projections(tmp_path)
    return tmp_path


def test_library_projection_matches_the_committed_files(repo: Path) -> None:
    assert check_equivalence(repo, items=_items()) == []


@pytest.mark.parametrize(
    "relative",
    (
        f".claude/agents/{AGENT_KEY}.md",
        f".codex/agents/{AGENT_KEY}.toml",
        f".opencode/agents/{AGENT_KEY}.md",
        f".claude/rules/{RULE_KEY}.md",
    ),
)
def test_altered_projection_is_reported(repo: Path, relative: str) -> None:
    target = repo.joinpath(*relative.split("/"))
    target.write_text(target.read_text(encoding="utf-8") + "\nlocal edit\n", encoding="utf-8")
    differences = check_equivalence(repo, items=_items())
    assert [Difference(relative, DifferenceNature.CONTENT)] == [
        Difference(item.path, item.nature) for item in differences
    ]


def test_altered_skill_copy_names_the_divergent_line(repo: Path) -> None:
    relative = f".codex/skills/{SKILL_KEY}/SKILL.md"
    target = repo.joinpath(*relative.split("/"))
    target.write_text(
        _skill_source(SKILL_KEY, SKILL_DESCRIPTION, "# Demo skill\n\nDo something else.\n"),
        encoding="utf-8",
    )
    differences = check_equivalence(repo, items=_items())
    assert [(item.path, item.nature) for item in differences] == [
        (relative, DifferenceNature.CONTENT)
    ]
    assert "first divergent body line" in differences[0].detail
    assert "Do something else." in differences[0].detail


def test_skill_disable_model_invocation_is_carried_not_a_gap(repo: Path) -> None:
    """`skill/v2` carries `disable-model-invocation`: a committed flag the
    Library content also carries reproduces byte-identically (no gap)."""

    flagged = SKILL_SOURCE.replace("---\n\n", "disable-model-invocation: true\n---\n\n", 1)
    for harness in (".claude", ".codex", ".opencode"):
        target = repo.joinpath(harness, "skills", SKILL_KEY, "SKILL.md")
        target.write_text(flagged, encoding="utf-8")
    from studio_client.canonical import CODEX_OPENAI_POLICY_TEXT

    policy_target = repo / ".codex" / "skills" / SKILL_KEY / "agents" / "openai.yaml"
    policy_target.parent.mkdir(parents=True, exist_ok=True)
    policy_target.write_text(CODEX_OPENAI_POLICY_TEXT, encoding="utf-8")
    items = [
        item
        if item.stable_key != SKILL_KEY
        else _skill_item(
            SKILL_KEY,
            SKILL_DESCRIPTION,
            SKILL_TEXT,
            files=((SKILL_AUX_PATH, SKILL_AUX_TEXT),),
            disable_model_invocation=True,
        )
        for item in _items()
    ]
    assert check_equivalence(repo, items=items) == []


def test_flagged_skill_projects_codex_openai_policy_but_unflagged_does_not() -> None:
    """A flagged skill projects `.codex/skills/<key>/agents/openai.yaml` (Codex
    cannot read the frontmatter flag, OpenCode can); an unflagged skill
    projects no policy file, and the flag stays verbatim in every SKILL.md."""

    from studio_client.canonical import CODEX_OPENAI_POLICY_TEXT, skill_projections_from

    flagged = SKILL_SOURCE.replace("---\n\n", "disable-model-invocation: true\n---\n\n", 1)
    projected = skill_projections_from(
        {
            SKILL_KEY: flagged,
            EXTRA_SKILL_KEY: _skill_source(EXTRA_SKILL_KEY, "Extra", EXTRA_SKILL_TEXT),
        },
        {SKILL_KEY: ((SKILL_AUX_PATH, SKILL_AUX_TEXT),)},
    )
    assert projected[f".codex/skills/{SKILL_KEY}/agents/openai.yaml"] == CODEX_OPENAI_POLICY_TEXT
    assert f".claude/skills/{SKILL_KEY}/agents/openai.yaml" not in projected
    assert f".opencode/skills/{SKILL_KEY}/agents/openai.yaml" not in projected
    assert not [path for path in projected if EXTRA_SKILL_KEY in path and "openai" in path]
    for harness in (".claude", ".codex", ".opencode"):
        assert (
            "disable-model-invocation: true" in projected[f"{harness}/skills/{SKILL_KEY}/SKILL.md"]
        )


def test_missing_codex_openai_policy_is_a_blocking_gap(repo: Path) -> None:
    """The Codex policy is a managed projection: when the Library carries the
    flag but the policy file is absent, it is a blocking `missing` gap."""

    flagged = SKILL_SOURCE.replace("---\n\n", "disable-model-invocation: true\n---\n\n", 1)
    for harness in (".claude", ".codex", ".opencode"):
        target = repo.joinpath(harness, "skills", SKILL_KEY, "SKILL.md")
        target.write_text(flagged, encoding="utf-8")
    items = [
        item
        if item.stable_key != SKILL_KEY
        else _skill_item(
            SKILL_KEY,
            SKILL_DESCRIPTION,
            SKILL_TEXT,
            files=((SKILL_AUX_PATH, SKILL_AUX_TEXT),),
            disable_model_invocation=True,
        )
        for item in _items()
    ]
    differences = check_equivalence(repo, items=items)
    assert [(item.path, item.nature) for item in differences] == [
        (f".codex/skills/{SKILL_KEY}/agents/openai.yaml", DifferenceNature.MISSING)
    ]
    assert differences[0].nature.blocking


def test_skill_unexpected_frontmatter_key_is_still_a_gap(repo: Path) -> None:
    """Any other frontmatter key the Library does not carry stays a gap."""

    relative = f".claude/skills/{SKILL_KEY}/SKILL.md"
    target = repo.joinpath(*relative.split("/"))
    target.write_text(
        SKILL_SOURCE.replace("---\n\n", "license: custom-only\n---\n\n", 1),
        encoding="utf-8",
    )
    differences = check_equivalence(repo, items=_items())
    assert [(item.path, item.nature) for item in differences] == [
        (relative, DifferenceNature.CONTENT)
    ]
    assert "license" in differences[0].detail


def test_skill_without_committed_projection_is_missing_in_every_harness(repo: Path) -> None:
    """Every skill is projected into every harness: a skill with no committed
    file is a blocking `missing` gap in each harness, never `unprojected`."""

    _write(
        repo / ".claude" / "skills" / EXTRA_SKILL_KEY / "SKILL.md",
        _skill_source(EXTRA_SKILL_KEY, "Extra", EXTRA_SKILL_TEXT),
    )
    items = [
        *_items(),
        _skill_item(EXTRA_SKILL_KEY, "Extra", EXTRA_SKILL_TEXT),
    ]
    differences = check_equivalence(repo, items=items)
    assert [(item.path, item.nature) for item in differences] == [
        (f".codex/skills/{EXTRA_SKILL_KEY}/SKILL.md", DifferenceNature.MISSING),
        (f".opencode/skills/{EXTRA_SKILL_KEY}/SKILL.md", DifferenceNature.MISSING),
    ]
    assert all(item.nature.blocking for item in differences)


def test_missing_and_unexpected_files_are_reported(repo: Path) -> None:
    codex_agent = repo / ".codex" / "agents" / f"{AGENT_KEY}.toml"
    codex_agent.unlink()
    stray = repo / ".claude" / "agents" / "handwritten.md"
    _write(stray, "---\nname: handwritten\n---\n")
    differences = {item.path: item.nature for item in check_equivalence(repo, items=_items())}
    assert differences[f".codex/agents/{AGENT_KEY}.toml"] is DifferenceNature.MISSING
    assert differences[".claude/agents/handwritten.md"] is DifferenceNature.UNEXPECTED


