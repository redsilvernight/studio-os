def test_bundle_from_resolved_carries_skill_files(repo: Path) -> None:
    """`bundle_from_resolved` rebuilds `skill_files` from `content['files']`,
    so the harness projections include the references."""

    from studio_client.canonical import build_offline_resolved
    from studio_client.projection_source import bundle_from_repo, bundle_from_resolved

    repo_bundle = bundle_from_repo(repo)
    assert repo_bundle.skill_files[SKILL_KEY] == ((SKILL_AUX_PATH, SKILL_AUX_TEXT),)

    resolved = build_offline_resolved(repo, AGENT_KEY)
    resolved_skills = [
        skill.model_copy(
            update={
                "content": {
                    **skill.content,
                    "files": [
                        {"path": path, "text": text} for path, text in repo_bundle.skill_files[key]
                    ],
                }
            }
        )
        for skill in resolved.skills
        for key in [skill.stable_key]
    ]
    rebuilt = bundle_from_resolved([resolved.model_copy(update={"skills": resolved_skills})])
    assert rebuilt.skill_files[SKILL_KEY] == ((SKILL_AUX_PATH, SKILL_AUX_TEXT),)

    from studio_client.canonical import skill_projections_from

    projected = skill_projections_from(rebuilt.skills, rebuilt.skill_files)
    for harness in (".claude", ".codex", ".opencode"):
        assert projected[f"{harness}/skills/{SKILL_KEY}/{SKILL_AUX_PATH}"] == SKILL_AUX_TEXT


def test_out_of_library_fields_are_listed_not_ignored(repo: Path) -> None:
    _write(repo / ".studio" / "studio-protocol.md", "---\nname: studio-protocol\n---\n")
    _write(repo / "AGENTS.md", "<!-- BEGIN GENERATED RULES from .agents/rules -->\n")
    differences = check_equivalence(repo, items=_items())
    excluded = {item.path for item in differences if item.nature is DifferenceNature.EXCLUDED}
    assert excluded == {".studio/studio-protocol.md", "AGENTS.md"}
    assert [item for item in differences if item.nature is not DifferenceNature.EXCLUDED] == []


def test_v1_rule_content_cannot_reproduce_the_rule_projection(repo: Path) -> None:
    """Documents why `rule/v2` is required: a v1 payload has no `applies_to`."""

