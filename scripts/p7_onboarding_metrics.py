"""P7 onboarding E2E — scripted scenario and reproducible bootstrap metrics.

Automates the reference scenario (AI Bootstrap audit §7, roadmap §9): a blank
Godot repository is seeded with a minimal `.agents/` project source, the local
`bootstrap` generator produces the Claude Code / OpenCode / Codex projections,
and the run is measured. Deterministic: same inputs, same bytes, same numbers —
running twice with no source change is byte-identical.

Measured (roadmap §9 / gate P7):
- files and bytes produced by `sync` (by kind, by harness);
- the permanent bootstrap kept in the repository (`permanent_bootstrap`);
- the manual actions a human performs to onboard, then to add a harness;
- harness parity: OpenCode and Codex are added without recreating any `.agents/`
  source (the canonical files stay byte-identical).

The metrics are published in `docs/AI_BOOTSTRAP_P7_METRICS.json` (machine) and
`docs/AI_BOOTSTRAP_P7_METRICS.md` (human).

Usage:
    uv run python -m scripts.p7_onboarding_metrics --root . --check   # exit 1 if stale
    uv run python -m scripts.p7_onboarding_metrics --root . --apply   # (re)write it
"""

